#!/usr/bin/env python3
"""Assign charities to volunteer site builders without building any charity twice.

Design: docs/volunteer-site-builders.md (approved by Clarke, 2026-11-21).

The record of who builds a charity is its one hub item, `[CHARITY-LANE] <domain
or org>`. A volunteer's hold on it is three things written together:

  label    `builder:volunteer`         the automated Site Builder skips it
  comment  <!-- charity-lane:claim holder=volunteer:<login> until=<UTC ISO> -->
  assignee the volunteer (best effort: GitHub drops an assignee who cannot see
           the repo, so the claim comment, not the assignee, is the record)

The ffcadmin work order and the sites list's build queue only display it.

Subcommands
  status       every open lane item with its holder, plus each volunteer's count
  claim        put one item on hold for one volunteer (refuses a held item)
  release      take a volunteer's hold off and return the item to the queue
  build-queue  write sites-list/build_queue.{csv,json} (run by 703 each week)

`claim` and `release` print their plan and change nothing unless `--apply` is
given. Repo access (729) and the ffcadmin work order are printed as follow-up
steps, never done here: 729 is gated, and ffcadmin is another repository.

Capacity (decision 5): one held charity per volunteer, up to three once one of
theirs has reached the charity's review. Stale (decision 6): no commit in the
charity's repo for 14 days. A stale hold is only ever reported; nothing here
releases a hold on its own.

Runs under `gh` auth (REST only; GraphQL is refused in cloud sessions).
"""

from __future__ import annotations

import argparse
import csv
import datetime as dt
import io
import json
import os
import pathlib
import re
import subprocess
import sys

HUB = "FreeForCharity/FFC-Cloudflare-Automation"
ORG = "FreeForCharity"
LANE = "charity-lane"
VOLUNTEER_LABEL = "builder:volunteer"
CLAIM_DAYS = 14
STALE_DAYS = 14
FIRST_CAP = 1
FULL_CAP = 3
# Lane stages at or past the charity's own review: a volunteer who has got one
# charity this far may hold up to FULL_CAP.
REVIEW_OR_LATER = {"lane:charity-review", "lane:gate3-done", "lane:live"}
STAGES = [
    "lane:build-ready", "lane:building", "lane:needs-info", "lane:built",
    "lane:validate", "lane:charity-review", "lane:gate3-done", "lane:live",
]
CLAIM_RE = re.compile(r"<!--\s*charity-lane:claim\s+holder=(\S+)\s+until=(\S+)\s*-->")
RELEASE_RE = re.compile(r"<!--\s*charity-lane:release\s+holder=(\S+)\s*-->")
LOGIN_RE = re.compile(r"^[A-Za-z0-9](?:[A-Za-z0-9]|-(?=[A-Za-z0-9])){0,38}$")
DOMAIN_RE = re.compile(r"^[a-z0-9-]+(\.[a-z0-9-]+)+$", re.I)
CATEGORY_RE = re.compile(r"^\s*[-*]?\s*Category:\s*`?([a-z_]+)`?", re.I | re.M)
CATEGORY_ORDER = {"food_water_shelter": 0, "veterans": 1, "other": 2, "unclassified": 3}

FOOTER = "\n---\n_Generated by [Claude Code](https://claude.ai/code)_"

QUEUE_COLUMNS = [
    "item", "charity", "category", "stage", "holder", "held_since", "repo",
    "preview_url", "last_repo_activity", "stale", "charity_maintainers",
]

# People who already work on a charity's repo, by side (charity, charity-likely,
# ffc-volunteer). Charity-side site managers are not holders: they never use a
# volunteer's slot and are never released, but a volunteer assigned to their
# charity must coordinate with them, so the queue shows them and a claim warns.
MAINTAINERS_CSV = pathlib.Path(__file__).resolve().parents[1] / "sites-list" / "site_maintainers.csv"
CHARITY_SIDES = {"charity", "charity-likely"}
RECENT_DAYS = 30


def load_maintainers(path: pathlib.Path = MAINTAINERS_CSV) -> list[dict]:
    try:
        with open(path, encoding="utf-8", newline="") as fh:
            return list(csv.DictReader(fh))
    except FileNotFoundError:
        return []


def charity_maintainers(repo: str, maintainers: list[dict]) -> list[dict]:
    return [m for m in maintainers if m.get("repo", "").lower() == repo.lower() and m.get("side") in CHARITY_SIDES]


def maintainer_notes(repo: str, maintainers: list[dict], now: dt.datetime) -> list[str]:
    notes = []
    for m in charity_maintainers(repo, maintainers):
        last = parse_iso((m.get("last_pr") or "") + "T00:00:00Z") if m.get("last_pr") else None
        recent = last is not None and now - last <= dt.timedelta(days=RECENT_DAYS)
        notes.append(f"`{m['login']}` ({m['side']}) works on {repo}"
                     + (f", last PR {m['last_pr']}: coordinate with them before building" if recent else ""))
    return notes


class Refused(Exception):
    """A claim or release the rules do not allow. Nothing was changed."""


# ---------------------------------------------------------------- GitHub I/O


def gh(path: str, method: str = "GET", body: dict | None = None):
    # 703 runs `build-queue` with a write-capable PAT; VOLUNTEER_ASSIGN_READ_ONLY=1
    # makes any write a hard error there, whatever a future change does.
    if method != "GET" and os.environ.get("VOLUNTEER_ASSIGN_READ_ONLY") == "1":
        raise RuntimeError(f"refusing gh api {method} {path}: VOLUNTEER_ASSIGN_READ_ONLY=1")
    cmd = ["gh", "api", "-X", method, path]
    if body is not None:
        cmd += ["--input", "-"]
    p = subprocess.run(cmd, input=json.dumps(body) if body is not None else None,
                       capture_output=True, text=True, encoding="utf-8")
    if p.returncode != 0:
        raise RuntimeError(f"gh api {method} {path} failed: {p.stderr.strip() or p.stdout.strip()}")
    return json.loads(p.stdout) if p.stdout.strip() else None


def gh_pages(path: str) -> list:
    out, page = [], 1
    sep = "&" if "?" in path else "?"
    while True:
        chunk = gh(f"{path}{sep}per_page=100&page={page}")
        out += chunk
        if len(chunk) < 100:
            return out
        page += 1


# ---------------------------------------------------------------- pure logic


def now_utc() -> dt.datetime:
    return dt.datetime.now(dt.timezone.utc).replace(microsecond=0)


def iso(t: dt.datetime) -> str:
    return t.strftime("%Y-%m-%dT%H:%M:%SZ")


def parse_iso(s: str) -> dt.datetime | None:
    try:
        return dt.datetime.fromisoformat(s.replace("Z", "+00:00"))
    except ValueError:
        return None


def labels_of(item: dict) -> set[str]:
    return {lab["name"] if isinstance(lab, dict) else lab for lab in item.get("labels", [])}


def stage_of(item: dict) -> str:
    found = [s for s in STAGES if s in labels_of(item)]
    return found[0] if found else "(no lane label)"


def charity_of(item: dict) -> str:
    return re.sub(r"^\[CHARITY-LANE\]\s*", "", item.get("title", "")).strip()


def repo_of(item: dict) -> str:
    """FFC-EX-<domain> from the title, or a repo the body names."""
    m = re.search(r"FreeForCharity/(FFC-EX-[A-Za-z0-9.\-]+)", item.get("body") or "")
    if m:
        return m.group(1).rstrip(".")
    name = charity_of(item)
    return f"FFC-EX-{name}" if DOMAIN_RE.match(name) else ""


def category_of(item: dict) -> str:
    m = CATEGORY_RE.search(item.get("body") or "")
    cat = m.group(1).lower() if m else "unclassified"
    return cat if cat in CATEGORY_ORDER else "unclassified"


def latest_claim(comments: list[dict]) -> dict | None:
    """Newest claim or release marker, oldest-first comment list in."""
    latest = None
    for c in comments:
        body = c.get("body") or ""
        for m in CLAIM_RE.finditer(body):
            latest = {"kind": "claim", "holder": m.group(1), "until": m.group(2),
                      "at": c.get("created_at", "")}
        for m in RELEASE_RE.finditer(body):
            latest = {"kind": "release", "holder": m.group(1), "at": c.get("created_at", "")}
    return latest


def holder_of(item: dict, comments: list[dict], now: dt.datetime) -> dict:
    """Who holds this item: a volunteer, the automated lane, or nobody."""
    labs = labels_of(item)
    claim = latest_claim(comments)
    if VOLUNTEER_LABEL in labs:
        if claim and claim["kind"] == "claim" and claim["holder"].startswith("volunteer:"):
            return {"kind": "volunteer", "login": claim["holder"].split(":", 1)[1],
                    "since": claim["at"], "until": claim["until"]}
        assignees = [a["login"] for a in item.get("assignees") or []]
        return {"kind": "volunteer", "login": assignees[0] if assignees else "?",
                "since": "", "until": "", "unrecorded": True}
    stage = stage_of(item)
    if stage == "lane:build-ready":
        if claim and claim["kind"] == "claim":
            until = parse_iso(claim["until"])
            if until and until > now:
                return {"kind": "automated", "since": claim["at"], "until": claim["until"]}
        return {"kind": "open"}
    if stage == "lane:needs-info":
        return {"kind": "waiting-on-charity"}
    return {"kind": "automated", "since": claim["at"] if claim else ""}


def holder_label(h: dict) -> str:
    return {
        "volunteer": f"Volunteer @{h.get('login', '?')}",
        "automated": "Automated builder",
        "open": "Open",
        "waiting-on-charity": "Waiting on the charity",
    }[h["kind"]]


def capacity_for(held_stages: list[str]) -> int:
    return FULL_CAP if any(s in REVIEW_OR_LATER for s in held_stages) else FIRST_CAP


def plan_claim(item: dict, comments: list[dict], login: str, held_by_login: list[dict],
               now: dt.datetime, adopt: bool = False) -> dict:
    """Decide a claim. Raises Refused; returns the writes to make otherwise.

    `held_by_login` is every open lane item this volunteer already holds.
    `adopt` records a volunteer who is ALREADY building this charity (the item
    may be past build-ready); it never takes an item from another volunteer or
    from an in-date automated lease.
    """
    if not LOGIN_RE.match(login):
        raise Refused(f"{login!r} is not a GitHub username")
    labs = labels_of(item)
    if item.get("state") != "open" or LANE not in labs:
        raise Refused(f"#{item.get('number')} is not an open {LANE} item")
    if "website-request" in labs:
        # Assigning a website-request issue starts 701 provisioning.
        raise Refused(f"#{item['number']} carries website-request; assigning it would start 701")
    h = holder_of(item, comments, now)
    if h["kind"] == "volunteer" and h.get("login") != login:
        raise Refused(f"#{item['number']} is already held by @{h.get('login')}")
    if h["kind"] == "volunteer" and h.get("login") == login and not h.get("unrecorded"):
        raise Refused(f"#{item['number']} is already held by @{login}; nothing to do")
    if h["kind"] == "automated" and not adopt:
        raise Refused(f"#{item['number']} is held by the automated lane ({stage_of(item)})")
    if adopt:
        # --adopt records a volunteer already building a charity; it must never
        # take one the Site Builder is working on right now (an in-date lease).
        c = latest_claim(comments)
        if c and c["kind"] == "claim" and not c["holder"].startswith("volunteer:"):
            until = parse_iso(c["until"])
            if until and until > now:
                raise Refused(f"#{item['number']} has an in-date automated lease until {c['until']}; "
                              "wait for it to end before adopting")
    if h["kind"] in ("waiting-on-charity",) and not adopt:
        raise Refused(f"#{item['number']} is waiting on the charity (lane:needs-info)")
    others = [i for i in held_by_login if i["number"] != item["number"]]
    cap = capacity_for([stage_of(i) for i in others])
    if len(others) >= cap:
        held = ", ".join(f"#{i['number']}" for i in others)
        raise Refused(f"@{login} already holds {held}; limit is {cap} until one reaches the charity's review"
                      if cap == FIRST_CAP else f"@{login} already holds {held}; limit is {cap}")
    stage = stage_of(item)
    add = [VOLUNTEER_LABEL]
    remove = []
    if stage == "lane:build-ready":
        add.append("lane:building")
        remove.append("lane:build-ready")
    until = iso(now + dt.timedelta(days=CLAIM_DAYS))
    marker = f"<!-- charity-lane:claim holder=volunteer:{login} until={until} -->"
    return {"item": item["number"], "login": login, "add_labels": add, "remove_labels": remove,
            "assign": login, "marker": marker, "until": until, "stage_after":
            "lane:building" if stage == "lane:build-ready" else stage,
            "repo": repo_of(item)}


def plan_release(item: dict, comments: list[dict], login: str, now: dt.datetime) -> dict:
    h = holder_of(item, comments, now)
    if h["kind"] != "volunteer" or h.get("login") != login:
        raise Refused(f"#{item['number']} is not held by @{login} (holder: {holder_label(h)})")
    stage = stage_of(item)
    add, remove = [], [VOLUNTEER_LABEL]
    if stage == "lane:building":
        add.append("lane:build-ready")
        remove.append("lane:building")
    return {"item": item["number"], "login": login, "add_labels": add, "remove_labels": remove,
            "unassign": login, "marker": f"<!-- charity-lane:release holder=volunteer:{login} -->",
            "repo": repo_of(item)}


def is_stale(last_activity: str, now: dt.datetime) -> str:
    """'yes' / 'no' / 'unknown'. Unknown never counts as stale."""
    t = parse_iso(last_activity) if last_activity else None
    if t is None:
        return "unknown"
    return "yes" if now - t > dt.timedelta(days=STALE_DAYS) else "no"


def queue_row(item: dict, comments: list[dict], last_activity: str, now: dt.datetime,
              maintainers: list[dict] | None = None) -> dict:
    h = holder_of(item, comments, now)
    repo = repo_of(item)
    return {
        "item": item["number"],
        "charity": charity_of(item),
        "category": category_of(item),
        "stage": stage_of(item).replace("lane:", ""),
        "holder": holder_label(h),
        "held_since": (h.get("since") or "")[:10],
        "repo": f"https://github.com/{ORG}/{repo}" if repo else "",
        "preview_url": (f"https://{charity_of(item)}/" if stage_of(item) == "lane:live" and DOMAIN_RE.match(charity_of(item))
                        else f"https://freeforcharity.github.io/{repo}/" if repo else ""),
        "last_repo_activity": (last_activity or "")[:10],
        "stale": is_stale(last_activity, now) if h["kind"] == "volunteer" else "",
        "charity_maintainers": " ".join(m["login"] for m in charity_maintainers(repo, maintainers or [])) if repo else "",
    }


def sort_rows(rows: list[dict]) -> list[dict]:
    # Open charities first (what a volunteer can take), then by priority category,
    # then oldest item first.
    return sorted(rows, key=lambda r: (r["holder"] != "Open", CATEGORY_ORDER.get(r["category"], 3),
                                       int(r["item"])))


def to_csv(rows: list[dict]) -> str:
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=QUEUE_COLUMNS, lineterminator="\n")
    w.writeheader()
    w.writerows(rows)
    return buf.getvalue()


# ---------------------------------------------------------------- live reads


def lane_items() -> list[dict]:
    items = gh_pages(f"repos/{HUB}/issues?labels={LANE}&state=open")
    return [i for i in items if "pull_request" not in i]


def item_comments(n: int) -> list[dict]:
    return gh_pages(f"repos/{HUB}/issues/{n}/comments")


def last_commit(repo: str) -> str:
    if not repo:
        return ""
    try:
        commits = gh(f"repos/{ORG}/{repo}/commits?per_page=1")
        return commits[0]["commit"]["committer"]["date"] if commits else ""
    except RuntimeError:
        pass
    # A session bound to other repos cannot read this one's commits; the search
    # API's pushed_at still can. Unreadable both ways -> 'unknown', never 'stale'.
    try:
        found = gh(f"search/repositories?q=repo:{ORG}/{repo}")
        items = (found or {}).get("items") or []
        return items[0].get("pushed_at", "") if items else ""
    except RuntimeError:
        return ""


def holds_of(login: str, items: list[dict], now: dt.datetime) -> list[dict]:
    out = []
    for i in items:
        if VOLUNTEER_LABEL in labels_of(i):
            h = holder_of(i, item_comments(i["number"]), now)
            if h.get("login") == login:
                out.append(i)
    return out


# ---------------------------------------------------------------- commands


def apply_writes(plan: dict) -> list[str]:
    """Write a plan. Order matters for a partial failure: the comment (the
    record) first, then the labels to add, then the assignee, and the labels to
    remove last, so a failure part way leaves the item over-labelled rather
    than with no lane label or no record."""
    n, notes = plan["item"], []
    gh(f"repos/{HUB}/issues/{n}/comments", "POST", {"body": plan["comment"]})
    if plan.get("add_labels"):
        gh(f"repos/{HUB}/issues/{n}/labels", "POST", {"labels": plan["add_labels"]})
    if plan.get("assign"):
        try:
            got = gh(f"repos/{HUB}/issues/{n}/assignees", "POST", {"assignees": [plan["assign"]]})
        except RuntimeError as e:
            got = None
            notes.append(f"assignee not set: {e}")
        if got is not None and plan["assign"] not in [a["login"] for a in (got or {}).get("assignees", [])]:
            notes.append(f"GitHub dropped @{plan['assign']} as assignee (no access to this repo yet); "
                         "the claim comment still records the hold")
    if plan.get("unassign"):
        try:
            gh(f"repos/{HUB}/issues/{n}/assignees", "DELETE", {"assignees": [plan["unassign"]]})
        except RuntimeError as e:
            notes.append(f"assignee not removed: {e}")
    for lab in plan.get("remove_labels", []):
        try:
            gh(f"repos/{HUB}/issues/{n}/labels/{lab}", "DELETE")
        except RuntimeError as e:
            notes.append(f"label {lab} not removed: {e}")
    return notes


def claim_comment(plan: dict) -> str:
    repo = plan["repo"] or "FFC-EX-<domain>"
    return "\n".join([
        plan["marker"],
        f"**Held by volunteer `{plan['login']}`** until {plan['until'][:10]} "
        f"(renewed by any commit in `{repo}`; flagged to Clarke after {STALE_DAYS} days with none).",
        "",
        "The automated Site Builder skips this item while it carries `builder:volunteer`.",
        "",
        "Follow-up steps (not done by the script):",
        f"- Repo access: workflow 729, repo `{repo}`, user `{plan['login']}`, permission `push` (github-prod gate).",
        "- ffcadmin work order: assign the volunteer and set `status:active-build`.",
        *([""] + ["Charity-side maintainers to coordinate with (not holders):"]
          + [f"- {n}" for n in plan["notes"]] if plan.get("notes") else []),
        "",
        "Design: docs/volunteer-site-builders.md",
        FOOTER,
    ])


def release_comment(plan: dict) -> str:
    repo = plan["repo"] or "FFC-EX-<domain>"
    return "\n".join([
        plan["marker"],
        f"**Released by volunteer `{plan['login']}`.** Back in the queue; their work stays in `{repo}`.",
        "",
        "Follow-up steps (not done by the script):",
        f"- Repo access: workflow 729 to lower `{plan['login']}` on `{repo}` to `pull`.",
        "- ffcadmin work order: unassign and set `status:needs-admin`.",
        FOOTER,
    ])


def get_item(n: int) -> dict:
    item = gh(f"repos/{HUB}/issues/{n}")
    if "pull_request" in item:
        raise Refused(f"#{n} is a pull request")
    return item


def cmd_claim(a) -> int:
    now = now_utc()
    item = get_item(a.item)
    comments = item_comments(a.item)
    plan = plan_claim(item, comments, a.volunteer, holds_of(a.volunteer, lane_items(), now), now, a.adopt)
    plan["notes"] = maintainer_notes(plan["repo"], load_maintainers(), now) if plan["repo"] else []
    plan["comment"] = claim_comment(plan)
    return report(plan, a.apply)


def cmd_release(a) -> int:
    item = get_item(a.item)
    plan = plan_release(item, item_comments(a.item), a.volunteer, now_utc())
    plan["comment"] = release_comment(plan)
    return report(plan, a.apply)


def report(plan: dict, apply: bool) -> int:
    print(("APPLY" if apply else "DRY RUN (nothing changed; pass --apply)") + f" item #{plan['item']}")
    for k in ("add_labels", "remove_labels", "assign", "unassign"):
        if plan.get(k):
            print(f"  {k}: {plan[k]}")
    for note in plan.get("notes", []):
        print(f"  CHARITY MAINTAINER: {note}")
    print("  comment:\n    " + plan["comment"].replace("\n", "\n    "))
    if apply:
        for note in apply_writes(plan):
            print(f"  NOTE: {note}")
        print("  done")
    return 0


def collect_rows(now: dt.datetime) -> list[dict]:
    maintainers = load_maintainers()
    rows = []
    for i in lane_items():
        rows.append(queue_row(i, item_comments(i["number"]), last_commit(repo_of(i)), now, maintainers))
    return sort_rows(rows)


def cmd_status(a) -> int:
    rows = collect_rows(now_utc())
    for r in rows:
        extra = f" stale={r['stale']}" if r["stale"] else ""
        print(f"#{r['item']:<5} {r['stage']:<16} {r['holder']:<28} {r['charity']}{extra}")
    print(f"{len(rows)} open lane items; {sum(r['holder'] == 'Open' for r in rows)} open to claim")
    return 0


def cmd_build_queue(a) -> int:
    now = now_utc()
    rows = collect_rows(now)
    out = pathlib.Path(a.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "build_queue.csv").write_text(to_csv(rows), encoding="utf-8", newline="\n")
    (out / "build_queue.json").write_text(
        json.dumps({"generated_at": iso(now), "source": f"{HUB} {LANE} items", "rows": rows},
                   indent=2) + "\n", encoding="utf-8", newline="\n")
    stale = [r for r in rows if r["stale"] == "yes"]
    print(f"build queue: {len(rows)} rows, {len(stale)} stale volunteer holds")
    for r in stale:
        print(f"::warning::Volunteer hold #{r['item']} ({r['charity']}, {r['holder']}) has had no repo "
              f"commit since {r['last_repo_activity']}; flag to Clarke (never released automatically).")
    return 0


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = p.add_subparsers(dest="cmd", required=True)
    sub.add_parser("status")
    c = sub.add_parser("claim")
    c.add_argument("--item", type=int, required=True)
    c.add_argument("--volunteer", required=True)
    c.add_argument("--adopt", action="store_true",
                   help="record a volunteer already building this charity (item may be past build-ready)")
    c.add_argument("--apply", action="store_true")
    r = sub.add_parser("release")
    r.add_argument("--item", type=int, required=True)
    r.add_argument("--volunteer", required=True)
    r.add_argument("--apply", action="store_true")
    b = sub.add_parser("build-queue")
    b.add_argument("--out-dir", default="sites-list")
    a = p.parse_args(argv)
    try:
        return {"status": cmd_status, "claim": cmd_claim, "release": cmd_release,
                "build-queue": cmd_build_queue}[a.cmd](a)
    except Refused as e:
        print(f"REFUSED: {e}")
        return 2
    except RuntimeError as e:
        print(f"ERROR: {e}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
